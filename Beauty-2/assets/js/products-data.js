(function () {
  "use strict";

  function formatPrice(amount) {
    return "₹ " + amount.toLocaleString("en-IN");
  }

  function starsHtml(rating) {
    var html = "";
    var i;

    for (i = 1; i <= 5; i += 1) {
      if (rating >= i) {
        html += '<i class="fa-solid fa-star"></i>';
      } else if (rating >= i - 0.5) {
        html += '<i class="fa-solid fa-star-half-stroke"></i>';
      } else {
        html += '<i class="fa-regular fa-star"></i>';
      }
    }

    return html;
  }

  function productUrl(id) {
    return "product.html?id=" + encodeURIComponent(id);
  }

  function getProduct(id) {
    return window.BOJ_PRODUCTS.find(function (item) {
      return item.id === id;
    });
  }

  function getProductIdByName(name) {
    var key = (name || "").trim().toLowerCase();
    var match = window.BOJ_PRODUCTS.find(function (item) {
      return item.name.toLowerCase() === key || (item.title && item.title.toLowerCase() === key);
    });
    return match ? match.id : null;
  }

  function initProductCardLinks() {
    document
      .querySelectorAll(
        ".boj-kedit__wish, .boj-kedit__cart, .boj-pdp-ymal__wish, .boj-pdp-ymal__add, .boj-shop__card-wish, .boj-shop__card-add"
      )
      .forEach(function (btn) {
        btn.addEventListener("click", function (e) {
          e.preventDefault();
          e.stopPropagation();
        });
      });

    document.querySelectorAll(".boj-kedit__card, .boj-pdp-ymal__card, .boj-shop__card").forEach(function (card) {
      var nameEl = card.querySelector(
        ".boj-kedit__name, .boj-pdp-ymal__name a, .boj-pdp-ymal__name, .boj-shop__card-name"
      );
      if (!nameEl) return;

      var id = card.getAttribute("data-boj-product-id") || getProductIdByName(nameEl.textContent);
      if (!id) return;

      card.setAttribute("data-boj-product-id", id);
      card.classList.add("boj-product-card--clickable");
      card.setAttribute("role", "link");
      card.setAttribute("tabindex", "0");

      function goToProduct() {
        window.location.href = productUrl(id);
      }

      card.addEventListener("click", function (e) {
        if (e.target.closest("button")) return;
        goToProduct();
      });

      card.addEventListener("keydown", function (e) {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          goToProduct();
        }
      });
    });

    document.querySelectorAll(".boj-shop__card-link").forEach(function (link) {
      var card = link.querySelector(".boj-kedit__card");
      if (!card) return;

      var nameEl = card.querySelector(".boj-kedit__name");
      var id = link.getAttribute("data-boj-product-id") || getProductIdByName(nameEl ? nameEl.textContent : "");
      if (!id) return;

      link.href = productUrl(id);
      link.setAttribute("data-boj-product-id", id);
    });

    document.querySelectorAll(".boj-pdp-ymal__name a").forEach(function (anchor) {
      var card = anchor.closest(".boj-pdp-ymal__card");
      var id = card ? card.getAttribute("data-boj-product-id") : null;
      if (id) anchor.href = productUrl(id);
    });
  }

  window.BOJHelpers = {
    formatPrice: formatPrice,
    starsHtml: starsHtml,
    productUrl: productUrl,
    getProduct: getProduct,
    getProductIdByName: getProductIdByName,
    initProductCardLinks: initProductCardLinks
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initProductCardLinks);
  } else {
    initProductCardLinks();
  }
})();
