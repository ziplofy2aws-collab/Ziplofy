const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const SystemSettings = require('../models/SystemSettings');

async function generatePrescriptionPdf({ workspace, doctor, contact, visit, prescription, clinicName }) {
  const dir = path.join(__dirname, '..', '..', 'uploads', 'prescriptions');
  fs.mkdirSync(dir, { recursive: true });
  const num = `RX-${Date.now().toString().slice(-8)}`;
  const filename = `${num}.pdf`;
  const filePath = path.join(dir, filename);

  const settings = await SystemSettings.findOne().lean();
  const brand = (settings && settings.appName) || clinicName || workspace.name || 'Clinic';

  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  const stream = fs.createWriteStream(filePath);
  doc.pipe(stream);

  doc.fontSize(18).font('Helvetica-Bold').fillColor('#0f766e').text(clinicName || workspace.name || 'Clinic');
  doc.fontSize(10).font('Helvetica').fillColor('#555')
    .text(doctor?.name ? `Dr. ${doctor.name}` : '')
    .text([doctor?.qualifications, doctor?.specialty].filter(Boolean).join(' · '));
  if (doctor?.room) doc.text(`Room ${doctor.room}`);
  doc.moveDown(0.4);
  doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#0f766e').lineWidth(1.5).stroke();
  doc.moveDown(0.8);

  doc.fontSize(16).font('Helvetica-Bold').fillColor('#111').text('PRESCRIPTION', { align: 'right' });
  doc.fontSize(9).font('Helvetica').fillColor('#666')
    .text(`Rx No: ${num}`, { align: 'right' })
    .text(`Date: ${visit?.date || new Date().toLocaleDateString('en-IN')}`, { align: 'right' });
  doc.moveDown(0.6);

  const patientName = visit?.patientName || contact?.name || 'Patient';
  doc.fontSize(11).font('Helvetica-Bold').fillColor('#111').text('Patient');
  doc.fontSize(10).font('Helvetica').fillColor('#333')
    .text(patientName)
    .text(visit?.patientPhone || contact?.phone || '');
  doc.moveDown(0.8);

  const vitals = visit?.vitals || {};
  const vitalBits = [
    vitals.bp && `BP ${vitals.bp}`,
    vitals.pulse && `Pulse ${vitals.pulse}`,
    vitals.temp && `Temp ${vitals.temp}`,
    vitals.weight && `Wt ${vitals.weight}`,
    vitals.spo2 && `SpO2 ${vitals.spo2}`,
  ].filter(Boolean);
  if (vitalBits.length) {
    doc.fontSize(9).fillColor('#555').text(`Vitals: ${vitalBits.join('  ·  ')}`);
    doc.moveDown(0.6);
  }

  const tableTop = doc.y;
  doc.rect(50, tableTop - 4, 495, 20).fill('#0f766e');
  doc.fillColor('#fff').font('Helvetica-Bold').fontSize(10);
  doc.text('#', 54, tableTop);
  doc.text('Medicine', 80, tableTop);
  doc.text('Dose', 280, tableTop);
  doc.text('Frequency', 360, tableTop);
  doc.text('Days', 480, tableTop);

  let y = tableTop + 24;
  const drugs = prescription.drugs || [];
  doc.font('Helvetica').fontSize(10).fillColor('#333');
  drugs.forEach((drug, i) => {
    if (i % 2 === 1) { doc.rect(50, y - 4, 495, 20).fill('#f3f4f6'); doc.fillColor('#333'); }
    doc.text(String(i + 1), 54, y);
    doc.text(String(drug.name || '').slice(0, 40), 80, y);
    doc.text(String(drug.dose || ''), 280, y);
    doc.text(String(drug.freq || ''), 360, y);
    doc.text(String(drug.days || ''), 480, y);
    y += 22;
  });
  if (!drugs.length) {
    doc.text('No medicines listed', 80, y);
    y += 22;
  }

  y += 16;
  if (prescription.advice) {
    doc.font('Helvetica-Bold').fontSize(10).fillColor('#111').text('Advice', 50, y);
    y = doc.y + 4;
    doc.font('Helvetica').fontSize(10).fillColor('#333').text(prescription.advice, 50, y, { width: 495 });
    y = doc.y + 12;
  }

  doc.fontSize(8).fillColor('#999').text(`Generated by ${brand}`, 50, 780, { align: 'center', width: 495 });
  doc.end();
  await new Promise((resolve, reject) => { stream.on('finish', resolve); stream.on('error', reject); });

  const base = (process.env.BACKEND_URL || 'https://api.wabapanel.com').replace(/\/+$/, '');
  const url = `${base}/api/uploads/prescriptions/${filename}`;
  return { url, filename, num };
}

module.exports = { generatePrescriptionPdf };
