window.getProductById = function (id) {
  if (!id) return window.PRODUCTS.bodie;
  const key = String(id).toLowerCase().trim();
  return window.PRODUCTS[key] || window.PRODUCTS.bodie;
};

window.getRelatedProducts = function (currentId, limit) {
  const max = limit || 4;
  return Object.values(window.PRODUCTS)
    .filter(p => p.id !== currentId && p.id !== 'franny')
    .slice(0, max);
};
