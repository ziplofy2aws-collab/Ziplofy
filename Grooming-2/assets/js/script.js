(function () {
  var toggle = document.querySelector("[data-gr2-menu-toggle]");
  var nav = document.querySelector("[data-gr2-nav]");
  var overlay = document.querySelector("[data-gr2-menu-overlay]");

  if (!toggle || !nav || !overlay) return;

  function setOpen(open) {
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    toggle.setAttribute("aria-label", open ? "Close menu" : "Open menu");
    nav.classList.toggle("is-open", open);
    overlay.hidden = !open;
    document.body.style.overflow = open ? "hidden" : "";
  }

  toggle.addEventListener("click", function () {
    setOpen(toggle.getAttribute("aria-expanded") !== "true");
  });

  overlay.addEventListener("click", function () {
    setOpen(false);
  });

  window.addEventListener("resize", function () {
    if (window.innerWidth > 900) setOpen(false);
  });
})();

(function () {
  var hero = document.querySelector("[data-gr2-hero]");
  if (!hero) return;

  var slides = hero.querySelectorAll(".gr2-hero__slide");
  var lines = hero.querySelectorAll("[data-gr2-hero-line]");
  var currentIndex = 0;
  var timerId = null;
  var intervalMs = 10000;

  if (!slides.length) return;

  function goTo(index) {
    currentIndex = (index + slides.length) % slides.length;

    slides.forEach(function (slide, slideIndex) {
      slide.classList.toggle("is-active", slideIndex === currentIndex);
    });

    lines.forEach(function (line, lineIndex) {
      var isActive = lineIndex === currentIndex;
      line.classList.toggle("is-active", isActive);
      line.setAttribute("aria-selected", isActive ? "true" : "false");
      line.tabIndex = isActive ? 0 : -1;
    });

    hero.dispatchEvent(
      new CustomEvent("gr2:hero-slide", { detail: { index: currentIndex } })
    );
  }

  function scheduleAutoplay() {
    if (timerId) window.clearInterval(timerId);

    timerId = window.setInterval(function () {
      goTo(currentIndex + 1);
    }, intervalMs);
  }

  function restartAutoplay(index) {
    goTo(index);
    scheduleAutoplay();
  }

  lines.forEach(function (line, index) {
    line.addEventListener("click", function () {
      restartAutoplay(index);
    });
  });

  hero.addEventListener("mouseenter", function () {
    if (timerId) {
      window.clearInterval(timerId);
      timerId = null;
    }
  });

  hero.addEventListener("mouseleave", function () {
    scheduleAutoplay();
  });

  scheduleAutoplay();
})();

(function () {
  var slider = document.querySelector("[data-gr2-cat-slider]");
  if (!slider) return;

  var viewport = slider.querySelector("[data-gr2-cat-viewport]");
  var track = slider.querySelector("[data-gr2-cat-track]");
  var pager = slider.querySelector("[data-gr2-cat-pager]");
  var pages = track ? track.querySelectorAll(".gr2-cat__page") : [];
  if (!viewport || !track || !pages.length) return;

  var index = 0;
  var touchStartX = 0;
  var touchDeltaX = 0;
  var mqlMobile = window.matchMedia("(max-width: 640px)");

  function isMobile() {
    return mqlMobile.matches;
  }

  function maxIndex() {
    return pages.length - 1;
  }

  function update() {
    if (!isMobile()) {
      track.style.transform = "";
      return;
    }

    track.style.transform = "translate3d(-" + index * 100 + "%, 0, 0)";

    if (pager) {
      pager.querySelectorAll(".gr2-cat__pager-btn").forEach(function (dot, dotIndex) {
        var active = dotIndex === index;
        dot.classList.toggle("is-active", active);
        dot.setAttribute("aria-selected", active ? "true" : "false");
      });
    }
  }

  function goTo(nextIndex) {
    if (!isMobile()) return;
    index = Math.max(0, Math.min(nextIndex, maxIndex()));
    update();
  }

  if (pager) {
    pager.innerHTML = "";
    pages.forEach(function (_page, pageIndex) {
      var btn = document.createElement("button");
      btn.type = "button";
      btn.className = "gr2-cat__pager-btn" + (pageIndex === 0 ? " is-active" : "");
      btn.setAttribute("aria-label", "Show category slide " + (pageIndex + 1));
      btn.setAttribute("aria-selected", pageIndex === 0 ? "true" : "false");
      btn.addEventListener("click", function () {
        goTo(pageIndex);
      });
      pager.appendChild(btn);
    });
  }

  viewport.addEventListener(
    "touchstart",
    function (event) {
      if (!isMobile()) return;
      touchStartX = event.touches[0].clientX;
      touchDeltaX = 0;
    },
    { passive: true }
  );

  viewport.addEventListener(
    "touchmove",
    function (event) {
      if (!isMobile()) return;
      touchDeltaX = event.touches[0].clientX - touchStartX;
    },
    { passive: true }
  );

  viewport.addEventListener(
    "touchend",
    function () {
      if (!isMobile() || Math.abs(touchDeltaX) < 40) return;
      if (touchDeltaX < 0) goTo(index + 1);
      else goTo(index - 1);
    },
    { passive: true }
  );

  viewport.addEventListener("keydown", function (event) {
    if (!isMobile()) return;
    if (event.key === "ArrowRight") {
      event.preventDefault();
      goTo(index + 1);
    }
    if (event.key === "ArrowLeft") {
      event.preventDefault();
      goTo(index - 1);
    }
  });

  mqlMobile.addEventListener("change", function () {
    index = 0;
    update();
  });

  window.addEventListener("resize", update);
  update();
})();

(function () {
  function initProductCarousel(section) {
    var dataKey = section.getAttribute("data-gr2-products");
    var products = dataKey ? window[dataKey] : null;
    if (!products || !products.length) return;

    var track = section.querySelector("[data-gr2-bs-track]");
    var viewport = section.querySelector("[data-gr2-bs-viewport]");
    var nextBtn = section.querySelector("[data-gr2-bs-next]");
    var prevBtn = section.querySelector("[data-gr2-bs-prev]");
    var progressBar = section.querySelector("[data-gr2-bs-progress]");
    if (!track || !viewport) return;

    function productHref(product) {
      if (product.id) {
        return "product.html?id=" + encodeURIComponent(product.id);
      }
      return "shop.html";
    }

    function buildPriceRow(product) {
      if (product.mrp) {
        return '<div class="gr2-bs__price-row"><span class="gr2-bs__mrp">' + product.mrp + "</span></div>";
      }

      return (
        '<div class="gr2-bs__price-row">' +
        '<strong class="gr2-bs__price">' + product.price + "</strong>" +
        '<del class="gr2-bs__was">' + product.was + "</del>" +
        '<span class="gr2-bs__save">' + product.save + "</span>" +
        "</div>"
      );
    }

    track.innerHTML = products
      .map(function (product, productIndex) {
        var loading = productIndex === 0 ? "" : ' loading="lazy"';
        var href = productHref(product);
        return (
          '<article class="gr2-bs__card">' +
          '<a href="' + href + '" class="gr2-bs__card-link">' +
          '<div class="gr2-bs__media">' +
          '<img src="' + product.image + '" alt="' + product.name + '" width="236" height="236"' + loading +
          ' decoding="async" />' +
          "</div>" +
          "<h3 class=\"gr2-bs__name\">" + product.name + "</h3>" +
          '<p class="gr2-bs__feature">' + product.feature + "</p>" +
          '<div class="gr2-bs__rating">' +
          '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
          '<span class="gr2-bs__rating-score">' + product.rating + "</span>" +
          '<span class="gr2-bs__rating-sep">|</span>' +
          '<span class="gr2-bs__reviews">(' + product.reviews + ")</span>" +
          "</div>" +
          buildPriceRow(product) +
          "</a>" +
          '<a href="' + href + '" class="gr2-bs__cart-btn">Add to Cart</a>' +
          "</article>"
        );
      })
      .join("");

    var cards = track.querySelectorAll(".gr2-bs__card");
    var index = 0;
    var touchStartX = 0;
    var touchDeltaX = 0;
    var mqlTouch = window.matchMedia("(max-width: 768px)");

    function isTouchMode() {
      return mqlTouch.matches;
    }

    function getGap() {
      return parseFloat(window.getComputedStyle(track).gap) || 16;
    }

    function getStep() {
      if (!cards.length) return 0;
      return cards[0].getBoundingClientRect().width + getGap();
    }

    function getMaxIndex() {
      var visible = viewport.getBoundingClientRect().width;
      var total = track.scrollWidth;
      var step = getStep();
      if (step <= 0) return 0;
      return Math.max(0, Math.ceil((total - visible) / step));
    }

    function updateProgress() {
      if (!progressBar) return;
      var maxIndex = getMaxIndex();
      var progress = maxIndex === 0 ? 100 : (index / maxIndex) * 100;
      progressBar.style.width = progress + "%";
    }

    function updateArrows() {
      var maxIndex = getMaxIndex();
      if (prevBtn) prevBtn.disabled = index <= 0;
      if (nextBtn) nextBtn.disabled = index >= maxIndex;
    }

    function updateTrack() {
      var step = getStep();
      var maxIndex = getMaxIndex();
      if (index > maxIndex) index = maxIndex;
      if (index < 0) index = 0;
      track.style.transform = "translate3d(-" + index * step + "px, 0, 0)";
      updateArrows();
      updateProgress();
    }

    function scrollNext() {
      if (index < getMaxIndex()) {
        index += 1;
        updateTrack();
      }
    }

    function scrollPrev() {
      if (index > 0) {
        index -= 1;
        updateTrack();
      }
    }

    if (prevBtn) prevBtn.addEventListener("click", scrollPrev);
    if (nextBtn) nextBtn.addEventListener("click", scrollNext);

    viewport.addEventListener("keydown", function (event) {
      if (event.key === "ArrowRight") {
        event.preventDefault();
        scrollNext();
      }
      if (event.key === "ArrowLeft") {
        event.preventDefault();
        scrollPrev();
      }
    });

    viewport.addEventListener(
      "touchstart",
      function (event) {
        if (!isTouchMode()) return;
        touchStartX = event.touches[0].clientX;
        touchDeltaX = 0;
      },
      { passive: true }
    );

    viewport.addEventListener(
      "touchmove",
      function (event) {
        if (!isTouchMode()) return;
        touchDeltaX = event.touches[0].clientX - touchStartX;
      },
      { passive: true }
    );

    viewport.addEventListener(
      "touchend",
      function () {
        if (!isTouchMode() || Math.abs(touchDeltaX) < 40) return;
        if (touchDeltaX < 0) scrollNext();
        else scrollPrev();
      },
      { passive: true }
    );

    mqlTouch.addEventListener("change", function () {
      index = 0;
      updateTrack();
    });

    window.addEventListener("resize", updateTrack);

    if (typeof ResizeObserver !== "undefined") {
      new ResizeObserver(updateTrack).observe(viewport);
    }

    updateTrack();

    window.dispatchEvent(new CustomEvent("gr2:motion-refresh"));
  }

  document.querySelectorAll("[data-gr2-product-carousel]").forEach(initProductCarousel);
})();

(function () {
  var reviews = window.GR2_REVIEWS;
  var section = document.querySelector("[data-gr2-reviews]");
  var track = section ? section.querySelector("[data-gr2-reviews-track]") : null;
  if (!section || !track || !reviews || !reviews.length) return;

  function buildStars() {
    return (
      '<div class="gr2-reviews__stars" aria-label="5 out of 5 stars">' +
      '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
      '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
      '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
      '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
      '<i class="fa-solid fa-star" aria-hidden="true"></i>' +
      "</div>"
    );
  }

  function buildCard(review) {
    return (
      '<article class="gr2-reviews__card">' +
      buildStars() +
      "<h3 class=\"gr2-reviews__title\">" + review.title + "</h3>" +
      '<p class="gr2-reviews__meta">' + review.author + "</p>" +
      '<p class="gr2-reviews__body">' + review.body + "</p>" +
      "</article>"
    );
  }

  function buildGroup(clone) {
    var attrs = clone ? ' class="gr2-reviews__group gr2-reviews__group--clone" aria-hidden="true"' : ' class="gr2-reviews__group"';
    return "<div" + attrs + ">" + reviews.map(buildCard).join("") + "</div>";
  }

  track.innerHTML = buildGroup(false) + buildGroup(true);

  window.dispatchEvent(new CustomEvent("gr2:motion-refresh"));
})();
